"""Register generator: regs/periph_soc.json is the single source of the
register map. This script writes

  tb/ral_model.py         pyuvm register model (uvm_reg_block / uvm_reg / uvm_reg_field)
  sw/periph_soc_regs.h    C header (addresses, field masks, reset values)
  docs/register_map.md    register documentation

usage: python3 tools/reggen.py           regenerate the three files
       python3 tools/reggen.py --check   exit 1 if any generated file is stale (CI)
"""
import json
import keyword
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = "regs/periph_soc.json"
HDR = "GENERATED by tools/reggen.py from regs/periph_soc.json. Do not edit by hand."


def load():
    spec = json.load(open(os.path.join(ROOT, SRC)))
    for b in spec["blocks"]:
        b["base"] = int(b["base"], 0)
        for r in b["regs"]:
            r["offset"] = int(r["offset"], 0)
            r["addr"] = b["base"] + r["offset"]
            r["reset"] = 0
            used = 0
            for f in r["fields"]:
                f.setdefault("volatile", False)
                mask = ((1 << f["bits"]) - 1) << f["lsb"]
                assert not used & mask, f"{b['name']}.{r['name']}: overlapping fields"
                assert f["name"].isidentifier() and not keyword.iskeyword(f["name"]), f"{f['name']}: not a usable field name"
                assert f["access"] in ("RW", "RO", "W1C"), f"{f['name']}: unsupported access {f['access']}"
                used |= mask
                r["reset"] |= f["reset"] << f["lsb"]
            r["mask"] = used
    return spec


def gen_python(spec):
    o = [f'"""pyuvm register model of {spec["name"]}. {HDR}"""',
         "from pyuvm import uvm_endianness_e, uvm_reg, uvm_reg_block, uvm_reg_field", "", ""]
    for b in spec["blocks"]:
        for r in b["regs"]:
            o.append(f"class {b['name']}_{r['name']}(uvm_reg):")
            o.append(f'    """{b["name"].upper()}.{r["name"]} @ {r["addr"]:#06x}: {r["doc"]}"""')
            o.append("")
            o.append(f'    def __init__(self, name="{b["name"]}_{r["name"]}"):')
            o.append("        super().__init__(name, 32)")
            o.append("")
            o.append("    def build(self):")
            for f in r["fields"]:
                o.append(f'        self.{f["name"]} = uvm_reg_field("{f["name"]}")')
                o.append(f'        self.{f["name"]}.configure(self, {f["bits"]}, {f["lsb"]}, "{f["access"]}", {f["volatile"]}, {f["reset"]:#x}, True, False, False)')
            o.append("")
            o.append("")
    o.append(f"class {spec['name']}_reg_block(uvm_reg_block):")
    o.append('    """All registers of the subsystem in one address map (`default_map`, base 0)."""')
    o.append("")
    o.append(f'    def __init__(self, name="{spec["name"]}"):')
    o.append("        super().__init__(name)")
    o.append('        self.default_map = self.create_map("default_map", 0, 4, uvm_endianness_e.UVM_LITTLE_ENDIAN)')
    for b in spec["blocks"]:
        for r in b["regs"]:
            n = f"{b['name']}_{r['name']}"
            o.append(f"        self.{n.lower()} = {n}()")
            o.append(f"        self.{n.lower()}.configure(self)")
            o.append(f"        self.{n.lower()}.build()")
            o.append(f'        self.default_map.add_reg(self.{n.lower()}, {r["addr"]:#06x}, "RW")')
    o.append("        self.lock_model()")
    o.append("")
    o.append("")
    o.append("# Per-register metadata for the RAL sequences: HDL path of each field")
    o.append("# (relative to the DUT top) for backdoor reads, tests to skip, bit-bash background.")
    meta = {}
    for b in spec["blocks"]:
        for r in b["regs"]:
            meta[f"{b['name']}_{r['name']}".lower()] = {
                "addr": r["addr"], "reset": r["reset"], "mask": r["mask"], "skip": r.get("skip", {}),
                "bit_bash_background": int(r.get("bit_bash_background", "0"), 0),
                "hdl": {f["name"]: (f"{b['hdl']}.{f['hdl']}" if b["hdl"] else f["hdl"]) for f in r["fields"] if f.get("hdl")},
            }
    o.append("REG_META = {")
    for k, v in meta.items():
        o.append(f"    {k!r}: {v!r},")
    o.append("}")
    return "\n".join(o) + "\n"


def gen_c(spec):
    g = f"{spec['name'].upper()}_REGS_H"
    o = [f"/* {HDR} */", f"#ifndef {g}", f"#define {g}", "", "#include <stdint.h>", ""]
    for b in spec["blocks"]:
        B = b["name"].upper()
        o.append(f"/* {B} block at {b['base']:#06x} */")
        o.append(f"#define {B}_BASE 0x{b['base']:08X}u")
        for r in b["regs"]:
            R = f"{B}_{r['name']}"
            o.append(f"#define {R}_OFFSET 0x{r['offset']:02X}u  /* {r['doc']} */")
            o.append(f"#define {R}_ADDR ({B}_BASE + {R}_OFFSET)")
            o.append(f"#define {R}_RESET 0x{r['reset']:08X}u")
            for f in r["fields"]:
                F = f"{R}_{f['name'].upper()}"
                o.append(f"#define {F}_LSB {f['lsb']}u")
                o.append(f"#define {F}_MASK 0x{((1 << f['bits']) - 1) << f['lsb']:08X}u  /* {f['access']} */")
        o.append("")
    o.append("#define REG32(addr) (*(volatile uint32_t *)(uintptr_t)(addr))")
    o += ["", f"#endif /* {g} */", ""]
    return "\n".join(o)


def gen_md(spec):
    o = ["# Register map", "", f"{HDR} The source is `{SRC}`.", "",
         "Access policies: **RW** read/write, **RO** read-only, **W1C** write 1 to clear. "
         "*Volatile* fields change without a bus write.", ""]
    for b in spec["blocks"]:
        o.append(f"## {b['name'].upper()} (base `{b['base']:#06x}`)")
        o.append("")
        o.append("| Address | Register | Reset | Fields | Notes |")
        o.append("|---|---|---|---|---|")
        for r in b["regs"]:
            fs = "<br>".join(f"[{f['lsb'] + f['bits'] - 1}:{f['lsb']}] `{f['name']}` {f['access']}{' (volatile)' if f['volatile'] else ''}"
                             for f in r["fields"])
            notes = r["doc"] + "".join(f" RAL skips {k}: {v}." for k, v in r.get("skip", {}).items())
            o.append(f"| `{r['addr']:#06x}` | {r['name']} | `{r['reset']:#x}` | {fs} | {notes} |")
        o.append("")
    o.append("Unmapped offsets and blocks return PSLVERR and read 0.")
    return "\n".join(o) + "\n"


def main():
    spec = load()
    outs = {"tb/ral_model.py": gen_python(spec), "sw/periph_soc_regs.h": gen_c(spec), "docs/register_map.md": gen_md(spec)}
    stale = []
    for path, text in outs.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if "--check" in sys.argv:
            if old != text:
                stale.append(path)
        elif old != text:
            open(full, "w").write(text)
            print(f"wrote {path}")
    if stale:
        print(f"stale generated files (run tools/reggen.py): {stale}")
        sys.exit(1)
    if "--check" in sys.argv:
        print("generated register files are up to date")


main()
